package com.mtpnda.biocue

import androidx.compose.ui.test.junit4.createComposeRule
import androidx.compose.ui.test.onNodeWithText
import androidx.compose.ui.test.performClick
import androidx.compose.ui.test.isDisplayed
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import com.mtpnda.biocue.core.data.local.DetectionDatabase
import com.mtpnda.biocue.core.data.local.StressEventEntity
import kotlinx.coroutines.runBlocking
import org.junit.Before
import org.junit.Rule
import org.junit.Test
import org.junit.runner.RunWith
import androidx.room.Room
import androidx.test.core.app.ApplicationProvider
import org.junit.After

@RunWith(AndroidJUnit4::class)
class EventLifecycleE2ETest {

    @get:Rule
    val composeTestRule = createComposeRule()

    private lateinit var db: DetectionDatabase

    @Before
    fun setup() {
        val context = ApplicationProvider.getApplicationContext<android.app.Application>()
        db = Room.databaseBuilder(
            context,
            DetectionDatabase::class.java, "sensor-database"
        ).allowMainThreadQueries().build()
    }

    @After
    fun teardown() {
        db.close()
    }

    @Test
    fun testOrphanedAutoEventAppearsInCaregiverDashboard() = runBlocking {
        // 1. Simulate an AUTO event generated by ScoringEngine 20 minutes ago
        val pastTime = System.currentTimeMillis() - (20 * 60 * 1000)
        db.eventDao().insertEvent(
            StressEventEntity(
                id = "test-auto-1",
                startTime = pastTime,
                endTime = null,
                triggerType = "AUTO",
                label = "NONE",
                isResolved = false
            )
        )

        // 2. Launch Caregiver Dashboard
        composeTestRule.setContent {
            val app = ApplicationProvider.getApplicationContext<android.app.Application>()
            val vm = MainViewModel(app)
            if (!vm.isCaregiverMode.value) {
                vm.toggleMode()
            }
            DashboardScreen(vm)
        }

        // 3. Verify it shows up in Pattern Review (Unresolved)
        composeTestRule.waitUntil(5000) {
            try {
                composeTestRule.onNodeWithText("Detected Spontaneous Spike").isDisplayed()
                true
            } catch (e: AssertionError) {
                false
            }
        }

        // 4. Caregiver resolves it as "OVERWHELMED"
        composeTestRule.onNodeWithText("Overwhelmed").performClick()

        // 5. Verify it is removed from Pattern Review
        composeTestRule.waitUntil(5000) {
            try {
                composeTestRule.onNodeWithText("All caught up").isDisplayed()
                true
            } catch (e: AssertionError) {
                false
            }
        }
        
        // 6. Verify it shows up in the Journal instead
        composeTestRule.onNodeWithText("OVERWHELMED").isDisplayed()
    }

    @Test
    fun testManualEventAppearsInJournalImmediately() = runBlocking {
        // 1. Simulate Wearer starting and ending a manual event successfully
        db.eventDao().insertEvent(
            StressEventEntity(
                id = "test-manual-1",
                startTime = System.currentTimeMillis() - 5000,
                endTime = System.currentTimeMillis(),
                triggerType = "MANUAL",
                label = "EXCITED",
                isResolved = true
            )
        )

        // 2. Launch Wearer Dashboard
        composeTestRule.setContent {
            val app = ApplicationProvider.getApplicationContext<android.app.Application>()
            val vm = MainViewModel(app)
            if (vm.isCaregiverMode.value) {
                vm.toggleMode()
            }
            DashboardScreen(vm)
        }

        // 3. Verify it's in the Journal immediately (since isResolved=true)
        composeTestRule.waitUntil(5000) {
            try {
                composeTestRule.onNodeWithText("EXCITED").isDisplayed()
                true
            } catch (e: AssertionError) {
                false
            }
        }
    }
}
